 page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('http://127.0.0.1:3018');
 await page.locator('.study-stage-nav button').first().click();
 for(const width of [320,375,390,680,760,768,900,1024,1440,1920]){
   await page.setViewportSize({width,height:900});
   check('no overflow '+width,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 }
 await page.setViewportSize({width:1366,height:768});
 await page.locator('#process').evaluate(el=>window.scrollTo({top:el.getBoundingClientRect().top+scrollY-100,behavior:'instant'}));
