 await page.waitForTimeout(750);
 check('study single column caption',await page.locator('.making-study-caption').evaluate(el=>getComputedStyle(el).display==='block'));
 await page.screenshot({path:'output/playwright/study-system-final.png'});
 await page.locator('.study-stage-nav button').nth(3).click();
 await page.waitForTimeout(750);
 await page.screenshot({path:'output/playwright/study-product-final.png'});
 const range=page.getByRole('slider',{name:'Idea to product stage'});
 await range.focus(); await page.keyboard.press('Home');
 check('range Home',await range.inputValue()==='0');
 await page.keyboard.press('ArrowRight');
 check('range arrow',await range.inputValue()==='1');
 await page.keyboard.press('End');
 check('range End',await range.inputValue()==='3');
 const rail=await range.boundingBox();
