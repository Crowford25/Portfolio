 check('asterisk drag',await range.inputValue()==='0');
 await page.locator('.study-scene').hover();
 check('cursor drag label',await page.locator('.custom-cursor span').textContent()==='DRAG');
 const cursorTransform=await page.locator('.custom-cursor').evaluate(el=>getComputedStyle(el).transform);
 check('cursor tracks pointer',cursorTransform!=='none');
 await page.locator('.making-study-caption p').hover();
 check('native selection cursor',await page.locator('html').evaluate(el=>!el.classList.contains('has-custom-cursor')));
 const links=await page.locator('.professional-links a').evaluateAll(els=>els.map(el=>({url:el.href,target:el.target,rel:el.rel})));
 check('LinkedIn configured',links.some(l=>l.url==='https://www.linkedin.com/in/wong-chee-chun-599980233'));
 check('GitHub reused',links.some(l=>l.url==='https://github.com/Crowford25'));
